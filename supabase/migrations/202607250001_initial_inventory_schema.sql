create extension if not exists pgcrypto;

create type public.product_unit as enum (
  'kg',
  'gram',
  'liter',
  'piece',
  'package'
);

create type public.stock_movement_type as enum (
  'opening',
  'incoming',
  'outgoing',
  'adjustment'
);

create table public.suppliers (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text,
  contact_person text,
  comment text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null,
  unit public.product_unit not null,
  minimum_stock numeric(12, 3) not null default 0 check (minimum_stock >= 0),
  purchase_price numeric(12, 4) not null default 0 check (purchase_price >= 0),
  opening_stock numeric(12, 3) not null default 0 check (opening_stock >= 0),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.stock_movements (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id),
  supplier_id bigint references public.suppliers(id),
  movement_type public.stock_movement_type not null,
  movement_date date not null,
  quantity_delta numeric(12, 3) not null,
  unit_price numeric(12, 4) not null default 0 check (unit_price >= 0),
  reason text,
  comment text,
  created_at timestamptz not null default now(),
  check (
    (movement_type in ('opening', 'incoming', 'adjustment'))
    or quantity_delta < 0
  ),
  check (
    movement_type <> 'incoming'
    or quantity_delta > 0
  )
);

create table public.inventory_counts (
  id bigint generated by default as identity primary key,
  inventory_date date not null,
  status text not null default 'draft' check (status in ('draft', 'confirmed')),
  comment text,
  confirmed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.inventory_count_items (
  id bigint generated by default as identity primary key,
  inventory_count_id bigint not null references public.inventory_counts(id) on delete cascade,
  product_id bigint not null references public.products(id),
  system_stock numeric(12, 3) not null,
  actual_stock numeric(12, 3) not null,
  difference numeric(12, 3) generated always as (actual_stock - system_stock) stored,
  unit_price numeric(12, 4) not null default 0,
  comment text,
  created_at timestamptz not null default now(),
  unique (inventory_count_id, product_id)
);

create table public.app_state (
  key text primary key check (key = 'inventory_draft'),
  value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create index suppliers_name_idx on public.suppliers (name);
create index products_name_idx on public.products (name);
create index products_category_idx on public.products (category);
create index stock_movements_product_date_idx on public.stock_movements (product_id, movement_date desc);
create index stock_movements_type_date_idx on public.stock_movements (movement_type, movement_date desc);
create index inventory_counts_date_idx on public.inventory_counts (inventory_date desc);

create or replace view public.current_product_stock as
select
  p.id,
  p.name,
  p.category,
  p.unit,
  p.minimum_stock,
  p.purchase_price,
  p.opening_stock,
  p.is_active,
  coalesce(p.opening_stock, 0) + coalesce(sum(sm.quantity_delta), 0) as current_stock,
  (coalesce(p.opening_stock, 0) + coalesce(sum(sm.quantity_delta), 0)) * p.purchase_price as current_value,
  (coalesce(p.opening_stock, 0) + coalesce(sum(sm.quantity_delta), 0)) <= p.minimum_stock as is_low_stock
from public.products p
left join public.stock_movements sm on sm.product_id = p.id
group by p.id;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger set_suppliers_updated_at
before update on public.suppliers
for each row execute function public.set_updated_at();

create trigger set_products_updated_at
before update on public.products
for each row execute function public.set_updated_at();

create trigger set_inventory_counts_updated_at
before update on public.inventory_counts
for each row execute function public.set_updated_at();

create trigger set_app_state_updated_at
before update on public.app_state
for each row execute function public.set_updated_at();

